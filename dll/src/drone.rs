//! Drones spawned by chips (`drone(x, y, z)` in scripts): the Vvc-700LD laser drone's own behavior call, fired from
//! the player's AC without the weapon equipped (RE_NOTES "Drone on kill").
//! - exe+6F9430 (producer = chr + 0x1F8, BehaviorParam_PC id, -1, *location, 2, weapon slot, *a7, f32, f32, 1, weapon
//!   slot, *a12, *a13, *a14, drone index, *a16) is what the weapon fire and the animation events call; the producer sets
//!   the team. The location in its explicit mode (dummy poly -1, mode 1, a 3x4 matrix with the translation in w) puts
//!   the drone anywhere. The other structs come from a template of one real drone call, with the owner handle (chr +8),
//!   the weapon slot and the slot's entry in module 38 (+0x140 + 0x40 x slot) patched in.
//! - The weapon slot must hold the drone weapon: internal slot DRONE_SLOT (an unused one of the game's setup loop) is
//!   loaded with it the way the game sets its internal slots (exe+903E69..903EB9: descriptor exe+15D6BE0 /
//!   exe+15D3370(desc, 0, equipId), exe+906590(slot - 0x10, &desc, 0), then exe+905AA0(module)). The module is rebuilt
//!   at each load, so the slot is checked before every spawn.

