static QUEUE: Mutex<Vec<([f32; 3], std::time::Instant)>> = Mutex::new(Vec::new());
/// A drone at this world position (game thread, next frame; dropped without a player AC).
pub fn queue(p: [f32; 3]) { queue_after(p, 0.0); }
/// `queue` after `secs`. A drone takes its target from the player's lock in its first frames and keeps it: spawned
/// right at a kill, it goes for the enemy just destroyed (RE_NOTES "Drone targets").
pub fn queue_after(p: [f32; 3], secs: f32) {
    let at = std::time::Instant::now() + std::time::Duration::from_secs_f32(secs.clamp(0.0, 10.0));
    QUEUE.lock().unwrap_or_else(|e| e.into_inner()).push((p, at));
}

#[repr(C, align(16))] struct B([u8; BUF]);

/// The drone weapon in DRONE_SLOT of the player's weapon module (`m`), set like the game's internal slots.
unsafe fn ensure_slot(base: usize, m: usize) -> bool {
    let slot = m + o::WEAPON_SLOT0 + DRONE_SLOT * o::WEAPON_SLOT_STRIDE;
    if mem::rd_u32(slot + o::SLOT_ID) == DRONE_WEAPON { return true; }
    let mut d = B([0; BUF]);
    let p = d.0.as_mut_ptr() as usize;
    mem::wr_i32(p + 4, -1); mem::wr_i32(p + 0x10, -1); mem::wr_i32(p + 0x18, -1);
    let init: unsafe extern "system" fn(usize, i32) -> usize = core::mem::transmute(base + FN_DESC_INIT);
    init(p + 0x18, -1);
    mem::wr_i32(p + 0x28, -1); mem::wr_i32(p + 0x2C, 0);
    let desc: unsafe extern "system" fn(usize, i32, u32) -> usize = core::mem::transmute(base + FN_DESC_WEAPON);
    desc(p, 0, DRONE_WEAPON);
    let set: unsafe extern "system" fn(usize, usize, u32) -> u64 = core::mem::transmute(base + FN_SET_SLOT);
    set(slot - 0x10, p, 0);
    let refresh: unsafe extern "system" fn(usize) -> u64 = core::mem::transmute(base + FN_WEAPONS_REFRESH);
    refresh(m);
    let ok = mem::rd_u32(slot + o::SLOT_ID) == DRONE_WEAPON;
    logf!("drone: weapon slot {} {}", DRONE_SLOT, if ok { "loaded with the laser drone" } else { "NOT loaded" });
    ok
}

/// Game thread, every frame (penalty.rs frame hook): the queued drones.
pub unsafe fn tick(base: usize) {
    let q: Vec<[f32; 3]> = {
        let mut all = QUEUE.lock().unwrap_or_else(|e| e.into_inner());
        if all.is_empty() { return; }
        let now = std::time::Instant::now();
        let (due, wait): (Vec<_>, Vec<_>) = all.drain(..).partition(|d| d.1 <= now);
        *all = wait;
        due.into_iter().map(|d| d.0).collect()
    };
    if q.is_empty() { return; }
    let wcm = mem::rd_usize(base + o::WORLDCHRMAN_GLOBAL);
    let chr = if wcm == 0 { 0 } else { mem::rd_usize(wcm + o::WCM_PLAYER) };
    if chr == 0 { return; }
    let mods = mem::rd_usize(chr + o::PLAYER_MODULES);
    let (m, m38) = (mem::rd_usize(mods + 8 * o::CHR_MOD_WEAPONS), mem::rd_usize(mods + 8 * 38));
    if m == 0 || m38 == 0 || mem::rd_usize(m) != base + o::WEAPONS_VTABLE || !ensure_slot(base, m) { return; }
    let (handle, k) = (mem::rd_u32(chr + 8), DRONE_SLOT as u32);
    let entry = (m38 + 0x140 + 0x40 * DRONE_SLOT) as u64;
    let behavior: FnBehavior = core::mem::transmute(base + FN_BEHAVIOR);
    let put32 = |b: &mut B, off: usize, v: u32| b.0[off..off + 4].copy_from_slice(&v.to_le_bytes());
    let put64 = |b: &mut B, off: usize, v: u64| b.0[off..off + 8].copy_from_slice(&v.to_le_bytes());
    for (n, p) in q.into_iter().enumerate() {
        let (mut a4, mut a7, mut a12, mut a13, mut a16) = (B([0; BUF]), B([0; BUF]), B([0; BUF]), B([0; BUF]), B([0; BUF]));
        a7.0[..0x80].copy_from_slice(&T_A7); a12.0[..0x80].copy_from_slice(&T_A12);
        a13.0[..0x80].copy_from_slice(&T_A13); a16.0[..0x80].copy_from_slice(&T_A16);
        put64(&mut a7, 0x10, entry); put32(&mut a7, 0x28, handle); put32(&mut a7, 0x30, k); put32(&mut a7, 0x48, handle); put32(&mut a7, 0x50, k);
        put64(&mut a12, 0x30, entry); put32(&mut a12, 0x48, handle); put32(&mut a12, 0x50, k); put32(&mut a12, 0x68, handle); put32(&mut a12, 0x70, k);
        put32(&mut a13, 0x08, handle); put32(&mut a13, 0x10, k);
        put32(&mut a16, 0x08, k);
        put32(&mut a4, 0, u32::MAX); a4.0[4] = 1;
        let f: [f32; 12] = [1.0, 0.0, 0.0, p[0], 0.0, 1.0, 0.0, p[1], 0.0, 0.0, 1.0, p[2]];
        for (i, v) in f.iter().enumerate() { a4.0[0x10 + 4 * i..0x14 + 4 * i].copy_from_slice(&v.to_le_bytes()); }
        let r = behavior(chr + 0x1F8, DRONE_BEHAVIOR, -1, a4.0.as_mut_ptr() as usize, 2, k as i32, a7.0.as_mut_ptr() as usize, 0.0, 0.0, 1, k,
            a12.0.as_mut_ptr() as usize, a13.0.as_mut_ptr() as usize, 0, (n % 6) as i32 + 1, a16.0.as_mut_ptr() as usize);
        logf!("drone: spawned at ({:.1}, {:.1}, {:.1}) -> {}", p[0], p[1], p[2], r & 0xFF);
    }
}
